"""Kindred's five mood faces: one geometry, generated for the app (src/faces.ts) and for
Android's notification + widget (vector drawables). Re-run after editing: python3 scripts/make-faces.py

Two palettes, picked in Settings. "kindred" (the default) is a diverging scale (blue good <->
red bad, warm-gray neutral) checked with the dataviz palette validator for colorblind separation
in both themes. "classic" follows the rainbow scale Daylio users know (teal, green, blue, orange,
red); it's familiar but teal and green are hard to tell apart with red-green colorblindness.
Feature ink is picked per face by contrast, so dark faces get light features and light ones dark."""
import json

LABELS = {5: "Great", 4: "Good", 3: "Okay", 2: "Bad", 1: "Awful"}

# palette id: (display name, {value: (light fill, dark fill)}). The first is the default.
PALETTES = {
    "kindred": ("Kindred", {
        5: ("#0E6E98", "#2E9AB8"),
        4: ("#52B3E0", "#86CCE6"),
        3: ("#DCD6CC", "#5C5852"),
        2: ("#EE9550", "#F6B37A"),
        1: ("#C73B37", "#E35A52"),
    }),
    "classic": ("Classic", {
        5: ("#17A589", "#26BF9D"),
        4: ("#7CBF3A", "#8DCB45"),
        3: ("#4A9FD8", "#55A8DD"),
        2: ("#F28C1C", "#F7992A"),
        1: ("#E8323F", "#EE4450"),
    }),
}
DARK_INK, LIGHT_INK = "#1F1D1A", "#FFFFFF"

# 24x24 face features. "fill" paths are solid; "stroke" paths are 1.7-wide round-capped lines.
EYES_DOTS = [("fill", "M7.3,10a1.3,1.3 0,1 0,2.6 0a1.3,1.3 0,1 0,-2.6 0Z"),
             ("fill", "M14.1,10a1.3,1.3 0,1 0,2.6 0a1.3,1.3 0,1 0,-2.6 0Z")]
FEATURES = {
    5: [("stroke", "M7,10.4Q8.6,8.2 10.2,10.4"), ("stroke", "M13.8,10.4Q15.4,8.2 17,10.4"),
        ("fill", "M7,13.2H17Q16.6,18.6 12,18.6Q7.4,18.6 7,13.2Z")],
    4: EYES_DOTS + [("stroke", "M7.8,14.4Q12,18.2 16.2,14.4")],
    3: EYES_DOTS + [("stroke", "M8.3,15.4H15.7")],
    2: EYES_DOTS + [("stroke", "M8,16.8Q12,13.4 16,16.8")],
    1: [("stroke", "M7.4,8.6L10.2,11.4"), ("stroke", "M10.2,8.6L7.4,11.4"),
        ("stroke", "M13.8,8.6L16.6,11.4"), ("stroke", "M16.6,8.6L13.8,11.4"),
        ("stroke", "M7.6,17.4Q12,12.8 16.4,17.4")],
}
CIRCLE = "M12,1A11,11 0,1 1,11.99,1Z"
RING = "#000000"  # drawn at low alpha so pale faces still read on pale backgrounds


def luminance(hexc):
    r, g, b = (int(hexc[i:i + 2], 16) / 255 for i in (1, 3, 5))
    lin = lambda c: c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def ink(fill):
    return LIGHT_INK if contrast(fill, LIGHT_INK) > contrast(fill, DARK_INK) else DARK_INK


# --- TypeScript for the app ---------------------------------------------------------------
faces = {str(v): {"label": label, "features": [{"kind": k, "d": d} for k, d in FEATURES[v]]} for v, label in LABELS.items()}
palettes = {
    pid: {
        "name": name,
        "colors": {
            str(v): {"fill": {"light": light, "dark": dark}, "ink": {"light": ink(light), "dark": ink(dark)}}
            for v, (light, dark) in colors.items()
        },
    }
    for pid, (name, colors) in PALETTES.items()
}
ts = (
    "// Generated by scripts/make-faces.py - edit that, not this file.\n\n"
    "export type FaceFeature = { kind: 'fill' | 'stroke'; d: string };\n"
    "export type FaceSpec = { label: string; features: FaceFeature[] };\n"
    "export type FaceColors = { fill: { light: string; dark: string }; ink: { light: string; dark: string } };\n"
    f"export type PaletteId = {' | '.join(json.dumps(p) for p in PALETTES)};\n"
    "export type Palette = { name: string; colors: Record<number, FaceColors> };\n\n"
    f"export const FACE_CIRCLE = {json.dumps(CIRCLE)};\nexport const FACE_STROKE_WIDTH = 1.7;\n\n"
    f"export const DEFAULT_PALETTE: PaletteId = {json.dumps(next(iter(PALETTES)))};\n\n"
    f"export const FACES: Record<number, FaceSpec> = {json.dumps(faces, indent=2)};\n\n"
    f"export const PALETTES: Record<PaletteId, Palette> = {json.dumps(palettes, indent=2)};\n"
)
open("src/faces.ts", "w").write(ts)

# --- Android vector drawables (light fills; the widget and notification use them) -----------
# The default palette is kindred_face_<v>; others are kindred_face_<palette>_<v>.
for i, (pid, (name, colors)) in enumerate(PALETTES.items()):
    for v, (light, _dark) in colors.items():
        inkc = ink(light)
        paths = [f'  <path android:fillColor="{light}" android:pathData="{CIRCLE}" />',
                 f'  <path android:strokeColor="{RING}" android:strokeAlpha="0.14" android:strokeWidth="0.8" '
                 f'android:pathData="{CIRCLE}" />']
        for kind, d in FEATURES[v]:
            if kind == "fill":
                paths.append(f'  <path android:fillColor="{inkc}" android:pathData="{d}" />')
            else:
                paths.append(f'  <path android:strokeColor="{inkc}" android:strokeWidth="1.7" '
                             f'android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{d}" />')
        xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
               f'<!-- {LABELS[v]} face, {name} palette. Generated by scripts/make-faces.py - edit that, not this file. -->\n'
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
               '  android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
               + "\n".join(paths) + "\n</vector>\n")
        suffix = f"{v}" if i == 0 else f"{pid}_{v}"
        open(f"modules/kindred-native/android/src/main/res/drawable/kindred_face_{suffix}.xml", "w").write(xml)

for pid, (name, colors) in PALETTES.items():
    for v, (light, dark) in colors.items():
        print(f"{pid:8} {v} {LABELS[v]:6} light {light} ink {ink(light)} ({contrast(light, ink(light)):.1f}:1)"
              f" | dark {dark} ink {ink(dark)} ({contrast(dark, ink(dark)):.1f}:1)")
